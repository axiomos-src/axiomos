#!/usr/bin/env python3
"""Rasterise the GUI bitmap font used by the AxiomOS compositor.

The kernel cannot parse TrueType at runtime, so the build step bakes a
monospaced 8x16 ASCII font out of DejaVu Sans Mono and writes it as a C array:
one byte per scanline, eight scanlines per glyph, MSB is the leftmost pixel.

Usage:
    python3 tools/mkgui_font.py
"""

import os

from PIL import Image, ImageDraw, ImageFont

CELL_W = 8
CELL_H = 16
FIRST = 32
LAST = 126

FONT_PATH = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
FONT_SIZE = 14
THRESHOLD = 96

OUTPUT = os.path.join(os.path.dirname(__file__), "..", "gui", "font8x16.c")


def render_glyph(font, char):
    """Render one character into a CELL_W x CELL_H bitmap."""
    image = Image.new("L", (CELL_W, CELL_H), 0)
    draw = ImageDraw.Draw(image)
    # Vertically centre the glyph using its own bounding box so that letters
    # without descenders sit on the common baseline.
    bbox = font.getbbox(char)
    ascent, descent = font.getmetrics()
    baseline = max(bbox[3], ascent) - 1
    x = (CELL_W - (bbox[2] - bbox[0])) // 2 - bbox[0]
    y = baseline - ascent + 1
    draw.text((x, y), char, fill=255, font=font)
    rows = []
    for row in range(CELL_H):
        value = 0
        for column in range(CELL_W):
            if image.getpixel((column, row)) >= THRESHOLD:
                value |= 0x80 >> column
        rows.append(value)
    return rows


def main():
    font = ImageFont.truetype(FONT_PATH, FONT_SIZE)
    glyphs = []
    for code in range(FIRST, LAST + 1):
        glyphs.append(render_glyph(font, chr(code)))

    lines = []
    lines.append("/* Generated by tools/mkgui_font.py - do not edit.")
    lines.append(" * Source: DejaVu Sans Mono %d px, 8x16 cell, MSB = left pixel. */" %
                 FONT_SIZE)
    lines.append("")
    lines.append("#include <axiom/types.h>")
    lines.append("")
    lines.append("const u8 gui_font8x16[%d][%d] = {" %
                 (LAST - FIRST + 1, CELL_H))
    for code, rows in zip(range(FIRST, LAST + 1), glyphs):
        label = chr(code) if code != 0x5C else "/"
        text = ", ".join("0x%02X" % row for row in rows)
        lines.append("    { %s },   /* %d '%s' */" % (text, code, label))
    lines.append("};")
    lines.append("")
    lines.append("const u8 gui_font_width = %d;" % CELL_W)
    lines.append("const u8 gui_font_height = %d;" % CELL_H)
    lines.append("const u8 gui_font_first = %d;" % FIRST)
    lines.append("const u8 gui_font_last = %d;" % LAST)
    lines.append("")

    with open(OUTPUT, "w") as handle:
        handle.write("\n".join(lines))
    print("font: %s (%d glyphs)" % (OUTPUT, len(glyphs)))


if __name__ == "__main__":
    main()
