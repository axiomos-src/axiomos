#!/usr/bin/env python3
"""Generate the loader's 5x7 dot-matrix font from a Linux PSF console font.

The UEFI loader cannot depend on asset files on the ESP before it has read
them, so the splash font is compiled into the binary.  Instead of hand-author-
ing 96 glyphs we derive them from the well-known VGA console font (PSF format,
8x16 cell) that Debian ships in the `kbd` package.  The downsampling is a
simple 5-of-7 decimation which keeps uppercase letterforms readable.

Usage:
    python3 tools/mkfont.py [--psf PATH] [--out PATH]
"""

import argparse
import gzip
import os
import sys

DEFAULT_PSF = "/usr/share/consolefonts/Lat15-VGA16.psf.gz"
OUT_HEADER = """/* AxiomOS UEFI loader - 5x7 dot-matrix font.
 *
 * AUTO-GENERATED by tools/mkfont.py from the console font "%s".
 * Do not edit by hand; run `make font` instead.
 *
 * Each glyph occupies 5 bytes; bit 7 of each byte is the leftmost pixel and
 * only 7 rows are used.
 */

const unsigned char font5x7[96][5] = {
"""


def read_psf(path: str) -> bytes:
    with open(path, "rb") as f:
        raw = f.read()
    if raw[:2] == b"\x1f\x8b":
        raw = gzip.decompress(raw)
    if raw[:2] not in (b"\x36\x04", b"PS"):
        raise SystemExit("%s: not a PSF1/PSF2 font" % path)
    if raw[:2] == b"\x36\x04":  # PSF1
        mode = raw[2] & 1
        charsize = raw[3]
        count = 512 if (raw[2] & 4) else 256
        hdr = 4
    else:  # PSF2
        hdr = 32
        charsize = raw[16]
        count = int.from_bytes(raw[20:24], "little")
    glyphs = []
    for i in range(count):
        start = hdr + i * charsize
        glyphs.append(raw[start:start + charsize])
    return glyphs, charsize


def downsample(glyph: bytes, charsize: int) -> list[int]:
    """Take an 8x16 glyph and produce 5 columns of 7 rows."""
    width = 8
    height = charsize // width if charsize % width == 0 else 16
    if height < 8:
        height = 16
    # columns 1..7 are the ink columns of a typical VGA glyph
    cols = [1, 2, 3, 4, 5]
    rows = [1, 3, 5, 7, 9, 11, 13]
    if height <= 8:
        rows = [0, 1, 2, 3, 4, 5, 6]
    out = []
    for col in cols:
        bits = 0
        for ridx, row in enumerate(rows):
            if row >= height:
                continue
            byte = glyph[row] if row < len(glyph) else 0
            if byte & (0x80 >> col):
                bits |= 0x80 >> ridx
        out.append(bits)
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--psf", default=DEFAULT_PSF)
    ap.add_argument("--out", default="boot/uefi/font5x7.c")
    args = ap.parse_args()

    if not os.path.exists(args.psf):
        print("font not found: %s (install the 'kbd' package)" % args.psf,
              file=sys.stderr)
        return 1

    glyphs, charsize = read_psf(args.psf)
    lines = [OUT_HEADER % os.path.basename(args.psf)]
    for code in range(32, 128):
        idx = code if code < len(glyphs) else ord("?")
        # PSF fonts start at U+0000 so index == code point for ASCII.
        data = downsample(glyphs[idx], charsize)
        name = chr(code) if code != 32 else "space"
        lines.append("    { %s },  /* 0x%02X '%s' */" %
                     (", ".join("0x%02X" % b for b in data), code, name))
    lines.append("};\n")
    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    with open(args.out, "w") as f:
        f.write("\n".join(lines))
    print("wrote %s (%d glyphs)" % (args.out, 96))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
